"""Write docs/HUNT_REPORT.md from the hunt index and the halo results.

Every number in that report is copied from data/hunt/index.json, data/hunt/<field>/hunt.json and
validation/halo_results.json by this script, so the report cannot drift from the results.

    python -m validation.hunt_report
"""

from __future__ import annotations

import json
import sys

from pipeline.spherex import ROOT

HUNT = ROOT / 'data' / 'hunt'
OUT = ROOT / 'docs' / 'HUNT_REPORT.md'

FLAG = {
    'colour_dependent_motion': 'motion differs between short and long wavelengths',
    'poor_model_fit': 'positions do not follow a clean path',
    'near_bright_star': 'in the glare of a bright star',
    'near_saturated_star': 'next to a saturated star',
    'beside_bright_source': 'in the wings of a much brighter source',
    'too_few_exposures_in_stack': 'too few exposures in the stack',
    'near_edge': 'at the edge of the images',
    'motion_explained_by_colour': 'shift explained by colour, not motion',
    'depends_on_one_visit': 'motion depends on a single visit',
    'negative_parallax': 'negative parallax',
    'unphysical_parallax': 'impossible parallax (closer than the nearest star)',
    'disagrees_with_gaia': 'Gaia measured a different motion',
    'gaia_2016_shows_it_here': 'Gaia saw a star at this spot in 2016',
    'wise_2015_shows_it_here': 'WISE saw a source at this spot around 2015',
    'two_visits_only': 'only two visits',
}


def f2(v, nd=2):
    return '—' if v is None else f'{v:.{nd}f}'


def main():
    idx = json.loads((HUNT / 'index.json').read_text())
    t, rec = idx['totals'], idx['recovery']
    L = []
    w = L.append
    w('# Planet X hunt: results of the blind search')
    w('')
    w(f"Generated by `python -m validation.hunt_report` from `data/hunt/index.json` (hunt index written {idx['generated_utc']}).")
    w('Every number below is copied from the result files by that script.')
    w('')
    w('## What was done')
    w('')
    w('The search (`pipeline/hunt.py`) is given a patch of sky and its SPHEREx exposures, and nothing else. It stacks each')
    w('visit in three wavelength bands, detects every source, links detections across visits, measures every linked source')
    w('in every exposure on native pixels, and applies the same pre-declared motion test as the rest of PARALLAX')
    w(f"(≥ {idx['thresholds']['motion_sigma']:.0f}σ and |μ|/σ_μ ≥ {idx['thresholds']['pm_over_error']:.0f}). Only then are catalogues consulted.")
    w('')
    w('| | |')
    w('|---|---|')
    w(f"| Fields searched | {t['fields']} ({t['area_deg2']:.2f} square degrees) |")
    w(f"| SPHEREx exposures used | {t['exposures']} |")
    w(f"| Sources found | {t['sources']} |")
    w(f"| Sources bright enough to motion-test | {t['motion_tested']} |")
    w(f"| Known fast movers in those fields | {rec['n_known']} |")
    w(f"| ... detected by the search | {rec['n_detected']} |")
    w(f"| ... **found as movers without being told** | **{rec['n_recovered']}** |")
    w(f"| Movers that no catalogue explains | **{len(idx['unexplained'])}** |")
    cls = idx['classes']
    w(f"| False alarms caught by the vetting tests (class `suspect`) | {cls.get('suspect', 0)} |")
    if idx.get('reach'):
        r = idx['reach']
        w(f"| Median 5σ depth of one visit at 3.8–5.0 µm (recovery and control fields) | {r['median_depth_ujy']:.0f} µJy |")
        w(f"| Distance at which a twin of WISE 0855 would still be detected | about {r['reach_ly']:.0f} light-years |")
    w('')
    w('Classes over all fields: ' + ', '.join(f'{k} {v}' for k, v in sorted(cls.items(), key=lambda kv: -kv[1])) + '.')
    w('')

    w('## Known movers: could the search find them blind?')
    w('')
    w('The catalogue position was used to choose the field (offset by a pseudo-random amount for the recovery fields) and,')
    w('after the search, to score it. It was never given to the search.')
    w('')
    w('| Field | Object | Type | Catalogue motion (″/yr) | Result | Measured motion (″/yr) | Significance | Decade check |')
    w('|---|---|---|---|---|---|---|---|')
    for f in idx['fields']:
        tr = f.get('truth')
        if not tr or tr['catalogue_pm_arcsec_yr'] < 0.2:
            continue
        m = next((m for m in f['movers'] if m.get('truth_match')), None)
        if tr['recovered']:
            res = 'found blind' if tr.get('parallax_fitted') else 'found blind (no parallax fit: speed includes parallax)'
        elif tr['detected']:
            res = f"seen, motion not confirmed ({tr.get('recovered_class')})"
        else:
            res = 'not found'
        sig = '—'
        if m and m.get('sigma') is not None:
            sig = '>30σ' if m['sigma'] >= 99 else f"{m['sigma']:.1f}σ"
        dec = '—'
        if m and m.get('catalogued_as'):
            dec = 'same motion in ' + m['catalogued_as']
        elif m and m['class'] == 'known_mover' and m.get('gaia'):
            dec = 'same motion in Gaia DR3 ' + str(m['gaia']['source_id'])
        w(f"| `{f['field_id']}` | {tr['name']} | {tr.get('spectral_type') or f.get('notes') or '—'} | {tr['catalogue_pm_arcsec_yr']:.2f} | {res} | "
          f"{f2(tr.get('measured_pm_arcsec_yr'))} | {sig} | {dec} |")
    w('')

    w('## Fields where nothing should move fast')
    w('')
    w('Blank extragalactic fields, and the fields of the three bright test stars. Any unexplained mover here is a false alarm.')
    w('')
    w('| Field | Kind | Sources tested | Unexplained movers | Known Gaia movers | Rejected by vetting |')
    w('|---|---|---|---|---|---|')
    for f in idx['fields']:
        tr = f.get('truth')
        if tr and tr['catalogue_pm_arcsec_yr'] >= 0.2:
            continue
        un = sum(1 for m in f['movers'] if m['class'] in ('candidate', 'stack_candidate', 'two_visit_candidate') and not m.get('catalogued_as') and not m.get('truth_match'))
        kn = sum(1 for m in f['movers'] if m['class'] == 'known_mover' or m.get('catalogued_as'))
        sp = sum(1 for m in f['movers'] if m['class'] == 'suspect')
        w(f"| `{f['field_id']}` | {f['kind']}{': ' + f['notes'] if f.get('notes') else ''} | {f['n_motion_tested']} | {un} | {kn} | {sp} |")
    w('')

    w('## Movers that no catalogue explains')
    w('')
    if not idx['unexplained']:
        w('**None.** Every source that passed the motion test is either the known object of its field, a Gaia star with the')
        w('same motion, or a source that CatWISE2020 already lists with the same motion.')
    else:
        w('These are **candidates, not discoveries**. Each needs independent confirmation.')
        w('')
        w('| Field | Source | RA, Dec (deg) | Class | Motion (″/yr) | Significance | Flags |')
        w('|---|---|---|---|---|---|---|')
        for m in idx['unexplained']:
            pm = m.get('pm_arcsec_yr') or (m.get('stack_motion') or {}).get('pm_arcsec_yr')
            sg = m.get('sigma') if m.get('sigma') is not None else (m.get('stack_motion') or {}).get('significance')
            w(f"| `{m['field_id']}` | {m['id']} | {m['ra']:.5f}, {m['dec']:.5f} | {m['class']} | {f2(pm)} | {f2(sg, 1)}σ | {', '.join(m.get('flags') or []) or '—'} |")
    w('')

    w('## False alarms the vetting caught')
    w('')
    w('Sources that passed the 5σ motion test and were then rejected, with the reason. Without these tests they would have')
    w('been reported as movers.')
    w('')
    w('| Field | Source | Claimed motion (″/yr) | Rejected because |')
    w('|---|---|---|---|')
    n = 0
    for f in idx['fields']:
        for m in f['movers']:
            if m['class'] != 'suspect':
                continue
            n += 1
            pm = m.get('pm_arcsec_yr') or (m.get('stack_motion') or {}).get('pm_arcsec_yr')
            w(f"| `{f['field_id']}` | {m['id']} | {f2(pm)} | {'; '.join(FLAG.get(k, k) for k in m.get('flags') or []) or '—'} |")
    if n == 0:
        w('| — | — | — | none |')
    w('')

    hp = ROOT / 'validation' / 'halo_results.json'
    if hp.is_file():
        h = json.loads(hp.read_text())
        w('## Brightness of the saturated variable stars, from their halo')
        w('')
        w('`pipeline/halo.py`: median surface brightness in an unsaturated ring around the star, compared between visits only')
        w(f"at matched wavelength. Thresholds: ≥ {h['thresholds']['sigma']:.0f}σ and ≥ {h['thresholds']['min_amplitude'] * 100:.0f}% change. Experimental.")
        w('')
        w('| Star | Ring (pixels) | Exposures used | Visit | Dates | Brightness vs first visit | Significance | Verdict |')
        w('|---|---|---|---|---|---|---|---|')
        for slug, d in h['targets'].items():
            vs = [v for v in d.get('visits', []) if v['n'] >= 5]
            for i, v in enumerate(vs):
                ratio = '1 (reference)' if i == 0 else f"{v['ratio']:.2f} ± {v['ratio'] * (v.get('err_vs_first') or 0):.2f}"
                sg = '—' if i == 0 or v.get('sigma') is None else f"{v['sigma']:.1f}σ"
                w(f"| {d.get('target', slug) if i == 0 else ''} | {'–'.join(str(int(x)) for x in d['ring_pixels']) if i == 0 else ''} | {d['n_used'] if i == 0 else ''} | "
                  f"{i + 1} | {v['start_utc'][:10]} – {v['end_utc'][:10]} | {ratio} | {sg} | {d['status'] if i == 0 else ''} |")
        cs = h['control_summary']
        w('')
        w(f"Controls: {cs['n_stars']} bright Gaia stars (G < 9.5) in the cached fields were run through the same code; "
          f"{cs['n_with_comparison']} were bright enough for a visit-to-visit comparison ({cs['n_comparisons']} comparisons). "
          f"**{cs['n_flagged_variable']} were flagged variable.** "
          + (f"Their median change was {cs['median_abs_change'] * 100:.1f}% and the largest {cs['max_abs_change'] * 100:.1f}%." if cs['median_abs_change'] is not None else ''))
        w("Barnard's Star, itself saturated and not a large-amplitude variable, is the third row of the table above.")
        w('')
    ip = ROOT / 'validation' / 'hunt_injection.json'
    if ip.is_file():
        inj = json.loads(ip.read_text())
        w('## How faint and how slow: blind injection test (SYNTHETIC, not real sources)')
        w('')
        w(inj['description'])
        w(f"Field `{inj['field']}`: {inj['n_exposures']} exposures over {inj['n_visits']} visits, baseline {inj['baseline_days']:.0f} days.")
        w('')
        label = {'recovered': 'found', 'seen_not_moving': 'seen, motion not proven', 'not_detected': 'too faint', 'correctly_still': 'still (correct)',
                 'false_alarm': '**FALSE ALARM**', 'wrong_speed': 'found, wrong speed'}
        w('| Injected speed | ' + ' | '.join(f'{f:.0f} µJy' for f in inj['fluxes_ujy']) + ' |')
        w('|---|' + '---|' * len(inj['fluxes_ujy']))
        for v in inj['speeds_arcsec_yr']:
            cells = []
            for f in inj['fluxes_ujy']:
                r = next((x for x in inj['results'] if abs(x['speed_arcsec_yr'] - v) < 1e-6 and abs(x['flux_ujy'] - f) < 1e-6), None)
                t_ = label.get(r['outcome'], r['outcome']) if r else 'not run'
                if r and r['outcome'] == 'recovered':
                    t_ += f" ({r['measured_pm_arcsec_yr']:.2f}″/yr)"
                cells.append(t_)
            w(f"| {'not moving' if v == 0 else f'{v:.0f}″/yr'} | " + ' | '.join(cells) + ' |')
        nrec = sum(1 for x in inj['results'] if x['outcome'] == 'recovered')
        nmov = sum(1 for x in inj['results'] if x['speed_arcsec_yr'] > 0)
        nfa = sum(1 for x in inj['results'] if x['outcome'] == 'false_alarm')
        w('')
        w(f"{nrec} of {nmov} moving injections were found; {nfa} of {len(inj['results']) - nmov} stationary injections were called movers; "
          f"besides the injections the search reported {inj['other_movers_reported']} movers in this field. "
          'For scale, WISE 0855 measures about 350 µJy in this band and moves 8″/yr.')
        w('')
    w('## Limits')
    w('')
    w('- The recovery fields were chosen because a known mover is there. They measure completeness, not a discovery rate.')
    w('- Motions are fitted without parallax when fewer than three visits are available; a nearby object\'s parallax then')
    w('  biases the linear motion (see WISE 0855).')
    w('- Stack-level candidates (too faint for single exposures) rest on two or three positions and are a weaker tier.')
    w('- Asteroids move out of a stack within hours and are rejected as outliers by design; this is not an asteroid search.')
    w('- A planet at several hundred au would move by arcminutes between visits (Earth\'s reflex motion), beyond these')
    w('  cutouts, and is expected to be too faint for one visit. This search targets nearby cold brown dwarfs and')
    w('  free-floating planets.')
    OUT.write_text('\n'.join(L) + '\n')
    print(f'wrote {OUT} ({len(L)} lines)')


if __name__ == '__main__':
    sys.exit(main())
