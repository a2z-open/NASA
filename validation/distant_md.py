"""Write docs/DISTANT_WORLDS.md from the result files, so the report cannot drift from the numbers.

    python -m validation.distant_md
"""
from __future__ import annotations

import json
from pathlib import Path

from astropy.time import Time

from validation import ledger

ROOT = Path(__file__).resolve().parents[1]


def day(mjd: float) -> str:
    return Time(mjd, format='mjd').strftime('%d %b %Y')


def main() -> None:
    d = json.loads((ROOT / 'validation' / 'distant_results.json').read_text())
    p9 = json.loads((ROOT / 'validation' / 'planet_nine.json').read_text())
    ok, problems = ledger.verify()
    L = []
    w = L.append
    w('# Distant worlds and Planet Nine: results')
    w('')
    w('Generated by `python -m validation.distant_md` from `validation/distant_results.json` and `validation/planet_nine.json`.')
    w('Do not edit by hand. Method and pass rules: `validation/distant/PROTOCOL.md` and `validation/distant/PROTOCOL_P9.md`.')
    w('Background reading with sources: `docs/PLANET_NINE_RESEARCH.md`.')
    w('')
    w('## In short')
    w('')
    w(f'- **{d["n_passed"]} of {d["n_tested"]} known distant worlds** were found without being told where they are, and placed at the right distance. '
      f'{d["false_objects"]} false objects were linked in the same fields.')
    for b in d['bodies']:
        if b['match']:
            m = b['match']
            w(f'- **{b["title"]}:** {m["r_fit_au"]:.2f} ± {m["r_err_au"]:.2f} AU measured, {m["r_true_au"]:.2f} AU from JPL Horizons '
              f'({"under 0.01" if m["distance_error_fraction"] < 1e-4 else format(100 * m["distance_error_fraction"], ".2f")} % apart), {m["n_detections"]} detections in {m["n_visits"]} visits.')
        else:
            w(f'- **{b["title"]}: not found.** {b["diagnostic"].get("why_missed", "")}')
    s = p9['search']
    w(f'- **Planet Nine mode:** {s["n_fields_three_visits"]} fields with three or more visits ({s["area_deg2_three_visits"]:.2f} square degrees). '
      f'{len(s["candidates"])} geometric candidate(s), {len(s["accepted"])} left after the brightness check. No detection.')
    if p9.get('faintest_synthetic_recovered_ujy'):
        w(f'- **Reach:** synthetic planets are recovered down to {p9["faintest_synthetic_recovered_ujy"]:.0f} µJy. The predicted Planet Nine is about '
          f'{p9["nominal"]["flux_ujy"]:.0f} µJy (V {p9["nominal"]["v"]:.1f} at {p9["nominal"]["r_au"]:.0f} AU). These images could not have found it.')
    w('')
    w('## 1. The test on known worlds')
    w('')
    w('JPL Horizons was used to choose which 16-arcminute patches to download, because these bodies move by degrees between')
    w('visits. Detection, linking and the orbit fit were given the images, Gaia DR3 and a WISE catalogue, and nothing else.')
    w('Each blind result was hashed into `validation/ledger.jsonl` before the ephemeris was opened to score it.')
    w('')
    w('| World | V | Exposures | Sources seen | In no catalogue | Tracklets | Result | Distance (AU) | JPL (AU) | Visits | Detections | Median offset | Locked (UTC) |')
    w('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for b in d['bodies']:
        m = b['match']
        w(f'| {b["title"]} | {b["vmag"]:.1f} | {b["n_exposures"]} | {b["n_peaks"]:,} | {b["n_orphans"]} | {b["n_tracklets"]} | '
          + ('**pass**' if b['passed'] else 'found, outside the pass rule' if b['recovered'] else '**not found**') + ' | '
          + (f'{m["r_fit_au"]:.2f} ± {m["r_err_au"]:.2f} | {m["r_true_au"]:.2f} | {m["n_visits"]} | {m["n_detections"]} | {m["median_sep_arcsec"]:.1f}″' if m else '— | — | — | — | —')
          + f' | entry {b["locked"]["entry"]}, {b["locked"]["time_utc"][:19]} |')
    w('')
    w('Pass rule, fixed in advance: at least 90 % of the linked detections within 12″ of the JPL position, distance within 5 %,')
    w('and no second object accepted in the same fields.')
    w('')
    for b in d['bodies']:
        w(f'### {b["title"]}')
        w('')
        o = b.get('object')
        if o:
            w(f'- Orbit fit: {o["n"]} detections, reduced χ² {o["chi2r"]:.2f}, scatter {o["rms_arcsec"]:.2f}″. Yearly parallax {o["parallax_arcsec"] / 60:.1f}′; '
              f'the body jumped {o["jump_deg"]:.1f}° between visits.')
            if o.get('a_au') and o.get('inclination_deg') is not None:
                w(f'- The same fit gives a semi-major axis of about {o["a_au"]:.0f} AU and an inclination of {o["inclination_deg"]:.0f}°. Indicative only: the arc is short.')
            w(f'- Mirrored-Earth test: the fit is {o["mirror_ratio"]:,.0f} times worse with the Earth on the wrong side of the Sun.')
            if o.get('spectrum'):
                lows = sorted(o['spectrum'], key=lambda r: r['value'])[:5]
                w(f'- Spectrum along the fitted orbit ({o.get("spectrum_exposures")} exposures, forced photometry): the deepest dips are at '
                  + ', '.join(f'{r["wavelength_um"]:.2f}' for r in sorted(lows, key=lambda r: r['wavelength_um'])) + ' µm. '
                  + (f'Earlier work found {b["title"]} covered in {o["surface"]["ice"]} ({o["surface"]["reference"]}); the dips are where that ice absorbs. '
                     if o.get('surface') else '') + 'Reflectance uses a 5772 K black body for sunlight, so it is indicative.')
        dg = b['diagnostic']
        for i, v in enumerate(dg.get('visits', [])):
            w(f'- Visit {i + 1} ({day(v["mjd_start"])} to {day(v["mjd_end"])}): {v["n_exposures"]} exposures, body detected in {v["n_detections_of_body"]} on {v["nights"]} night(s) (after the fact).')
        if dg.get('why_missed'):
            w(f'- Why it was missed: {dg["why_missed"]}')
        if dg.get('one_visit_fit'):
            f = dg['one_visit_fit']
            w(f'- After the fact: its track in one visit ({f["n"]} detections, {f["nights"]} nights, {f["rate_arcsec_day"]:.0f}″ a day) fitted alone gives '
              f'{f["r_au"]:.1f} ± {f["r_err_au"]:.1f} AU against {f["r_true_au"]:.1f} AU. This is not counted as a pass.')
        w('')
    w('## 2. Planet Nine mode')
    w('')
    w(f'Thresholds were hashed into the ledger before each run. Four versions were needed, each change is explained in `validation/distant/PROTOCOL_P9.md`,')
    w('and the last one added a brightness rule after two real candidates had been seen.')
    w('')
    w('| Field | Visits | Single-visit sources | Pairs | Triples |')
    w('|---|---|---|---|---|')
    for f in s['fields']:
        w(f'| `{f["field_id"]}` | {f["n_visits"]} | {f["n_single_visit_sources"]} | {f["n_pairs"]} | {f["n_triples"]} |')
    w('')
    if s['candidates']:
        w('### Geometric candidates, and why each is rejected')
        w('')
        w('| Field | Fitted distance (AU) | Brightness (µJy) | A Jupiter twin there (µJy) | Verdict |')
        w('|---|---|---|---|---|')
        for c in s['candidates']:
            w(f'| `{c["field_id"]}` | {c["r_au"]:.0f} ± {c["r_err_au"]:.0f} | {c["flux_ujy"]:,.0f} | {c["jupiter_twin_ujy"]:.1f} | '
              + ('too bright to be a planet' if c['too_bright_for_a_planet'] else 'fails the mirror test' if not c['passes_mirror_test'] else '**unconfirmed candidate**') + ' |')
        w('')
    inj = p9.get('injection')
    if inj:
        w('### Synthetic planets (never real)')
        w('')
        w(f'{len(inj["results"])} synthetic planets were added to the real images of `{inj["field"]}` ({inj["n_exposures"]} exposures, {inj["n_visits"]} visits) and searched for.')
        w('')
        w('| Distance | ' + ' | '.join(f'{f:.0f} µJy' for f in inj['fluxes_ujy']) + ' |')
        w('|---|' + '---|' * len(inj['fluxes_ujy']))
        label = {'recovered': 'found', 'too_faint': 'too faint', 'seen_not_linked': 'seen, not linked', 'wrong_distance': 'wrong distance', 'outside_field': 'left the field'}
        for r in inj['r_au']:
            cells = []
            for f in inj['fluxes_ujy']:
                x = next((q for q in inj['results'] if abs(q['r_au'] - r) < 1e-6 and abs(q['flux_ujy'] - f) < 1e-6), None)
                cells.append((label.get(x['outcome'], x['outcome']) + (f' ({x["r_fit_au"]:.0f} AU)' if x.get('r_fit_au') else '')) if x else 'not run')
            w(f'| {r:.0f} AU | ' + ' | '.join(cells) + ' |')
        w('')
        w(f'False links in that field: {inj["false_triples"]}.')
        w('')
    if p9.get('reach'):
        w('### How far away a world could be and still be found in these images')
        w('')
        w('| World | Reference brightness | Farthest distance (AU) |')
        w('|---|---|---|')
        for r in p9['reach']:
            w(f'| {r["world"]} | {r["reference"]} | {r["max_distance_au"]:.0f} |')
        w('')
        w('Reflected sunlight falls as the fourth power of distance, and a flat albedo is assumed. The fields are 20 arcminutes wide, so a body')
        w('closer than about 450 AU leaves the field between visits. In practice only a body the size of Jupiter was within reach, and WISE has')
        w('already ruled that out (Luhman 2014).')
        w('')
    w('## 3. The lock record')
    w('')
    w(f'`validation/ledger.jsonl`: {len(ledger.entries())} entries; chain and files {"verify" if ok else "DO NOT verify: " + "; ".join(problems)}.')
    w('The record is local and its clock is this computer\'s clock. It proves order and integrity to anyone who trusts the machine.')
    w('')
    w('| Entry | Time (UTC) | What was locked | Hash |')
    w('|---|---|---|---|')
    for e in ledger.entries():
        w(f'| {e["seq"]} | {e["time_utc"][:19]} | {e["label"]} | `{e["hash"][:16]}…` |')
    w('')
    (ROOT / 'docs' / 'DISTANT_WORLDS.md').write_text('\n'.join(L) + '\n')
    print(f'docs/DISTANT_WORLDS.md written ({len(L)} lines)')


if __name__ == '__main__':
    main()
